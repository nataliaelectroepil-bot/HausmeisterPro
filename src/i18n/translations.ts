export function translateStatusLabel(status: TaskStatus, lang: LanguageCode): string {
  if (status === 'offen') return UI_DICTIONARY[lang]['common.open'];
  if (status === 'in_bearbeitung') return UI_DICTIONARY[lang]['common.inProgress'];
  return UI_DICTIONARY[lang]['common.done'];
}

export function translatePriorityLabel(priority: TaskPriority, lang: LanguageCode): string {
  if (priority === 'dringend') return UI_DICTIONARY[lang]['common.urgent'];
  if (priority === 'hoch') return UI_DICTIONARY[lang]['common.high'];
  return UI_DICTIONARY[lang]['common.normal'];
}

export function translateRoleLabel(role: UserRole, lang: LanguageCode, short = false): string {
  if (role === 'admin') {
    return short ? UI_DICTIONARY[lang]['role.adminShort'] : UI_DICTIONARY[lang]['role.admin'];
  }
  if (role === 'client_hausverwaltung') {
    return short ? UI_DICTIONARY[lang]['role.clientShort'] : UI_DICTIONARY[lang]['role.client'];
  }
  return short ? UI_DICTIONARY[lang]['role.workerShort'] : UI_DICTIONARY[lang]['role.worker'];
}

